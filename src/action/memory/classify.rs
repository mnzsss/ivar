//! Classification of captured prompts and tool calls: who wrote a prompt, what
//! a tool did to the hall, and how much of the call is worth keeping.

use crate::domain::observation::{Origin, ToolEffect};

const READ_TOOLS: [&str; 11] = [
    "Read",
    "Glob",
    "Grep",
    "LS",
    "NotebookRead",
    "read",
    "grep",
    "find",
    "ls",
    "glob",
    "list",
];
const READ_COMMANDS: [&str; 14] = [
    "git status",
    "git log",
    "git diff",
    "git show",
    "ls",
    "cat",
    "rg",
    "grep",
    "pwd",
    "echo",
    "which",
    "head",
    "tail",
    "wc",
];
const HARNESS_PREFIXES: [&str; 7] = [
    "<task-notification>",
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<local-command-caveat>",
    "<command-name>",
    "<system-reminder>",
    "Caveat: The messages below were generated by the user while running local commands",
];
const RESULT_LIMIT_CHARS: usize = 512;

#[must_use]
pub fn tool_effect(name: &str, input: &serde_json::Value, failed: bool) -> ToolEffect {
    if failed {
        return ToolEffect::Failed;
    }
    if READ_TOOLS.contains(&name) || name.ends_with("graph_explore") {
        return ToolEffect::Reads;
    }
    if matches!(name, "Bash" | "bash") {
        let command = input
            .get("command")
            .and_then(serde_json::Value::as_str)
            .unwrap_or("")
            .trim_start();
        let composed = command.contains(['|', ';', '&', '>', '`', '$']);
        let reads = READ_COMMANDS
            .iter()
            .any(|c| command == *c || command.starts_with(&format!("{c} ")));
        return if reads && !composed {
            ToolEffect::Reads
        } else {
            ToolEffect::Writes
        };
    }
    ToolEffect::Writes
}

#[must_use]
pub fn prompt_origin(text: &str) -> Origin {
    if HARNESS_PREFIXES
        .iter()
        .any(|prefix| text.trim_start().starts_with(prefix))
    {
        Origin::Harness
    } else {
        Origin::User
    }
}

#[must_use]
pub fn tool_body(
    name: &str,
    input: &serde_json::Value,
    effect: ToolEffect,
    result: Option<&str>,
) -> String {
    if effect == ToolEffect::Reads {
        let path = ["file_path", "filePath", "path", "pattern"]
            .iter()
            .find_map(|k| input.get(*k))
            .cloned()
            .unwrap_or_default();
        return serde_json::json!({ "tool": name, "path": path }).to_string();
    }
    let result: String = result
        .unwrap_or("")
        .chars()
        .take(RESULT_LIMIT_CHARS)
        .collect();
    serde_json::json!({ "tool": name, "input": input, "result": result }).to_string()
}

